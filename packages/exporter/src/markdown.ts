/** Path and query of a collection request; the host comes from the environment. */
function postmanPath(r: PostmanRequest): string {
  const url = r.url
  return url.path ? `${url.path}${url.query ? `?${url.query}` : ''}` : url.text
}

function postmanRequestSection(ctx: Ctx, r: PostmanRequest, from: string): string {
  const callers = r.siteIds
    .map((id) => ctx.index.requests.get(id))
    .filter((s): s is RequestSite => Boolean(s))
  const resolved = urlText(r.url)
  // `200 OK` already says its status; other names get it added.
  const examples = r.examples.map(
    (e) =>
      `${text(e.name)}${e.status !== undefined && !e.name.startsWith(String(e.status)) ? ` (${e.status})` : ''}`,
  )
  const caller = (s: RequestSite) => {
    const byCode = s.contract?.requestId === r.id && s.contract.by === 'code'
    return `${siteLink(ctx, s, from)} in ${ownerText(ctx, s, from)}${byCode ? ' (matched by name and method)' : ''}`
  }
  return doc([
    `#### ${anchor(r.id)}${text(r.name)}`,
    facts([
      ['Request', code(`${r.method} ${r.url.text}`)],
      ['URL', resolved !== r.url.text ? code(resolved) : undefined],
      [
        'Unresolved variables',
        r.unresolved?.length ? r.unresolved.map((v) => code(`{{${v}}}`)).join(', ') : undefined,
      ],
      ['Called by', callers.length === 0 ? 'nothing in the code' : callers.map(caller).join('<br>')],
      ['Examples', examples.join(', ') || undefined],
    ]),
    r.flags.map((f) => `> ⚠ **${f.kind}**: ${text(f.message)}`).join('\n>\n'),
    r.bodyType && `**Request body** ${typeBlock(ctx, r.bodyType, from)}`,
    r.responseType && `**Response** (from the examples) ${typeBlock(ctx, r.responseType, from)}`,
  ]).trimEnd()
}

/** Nested list of components, with links to their docs. */
function componentTree(ctx: Ctx, rootId: string, from: string): string {
  const lines: string[] = []
  const label = (c: Component) => {
    const n = ctx.index.requestsByComponent.get(c.id)?.length ?? 0
    return [componentLink(ctx, c.id, from), c.kind, n > 0 ? `⇄ ${plural(n, 'request')}` : '']
      .filter(Boolean)
      .join(' · ')
  }
  const walk = (id: string, depth: number, path: Set<string>) => {
    const component = ctx.index.components.get(id)
    if (!component) return
    for (const ref of component.children) {
      const indent = '  '.repeat(depth)
      const notes = [ref.conditional && 'conditional', ref.dynamic && 'dynamic'].filter(Boolean).join(', ')
      const suffix = notes ? ` · ${notes}` : ''
      const target = ref.componentId ? ctx.index.components.get(ref.componentId) : undefined
      if (target) {
        const cycle = path.has(target.id)
        lines.push(`${indent}- ${label(target)}${suffix}${cycle ? ' · (cycle)' : ''}`)
        if (!cycle) walk(target.id, depth + 1, new Set([...path, target.id]))
      } else {
        const where = ref.factory ?? ref.module
        lines.push(
          `${indent}- ${code(ref.name)} · ${ref.resolution}${where ? ` (${code(where)})` : ''}${suffix}`,
        )
      }
    }
  }
  const root = ctx.index.components.get(rootId)
  if (!root) return 'The page component is missing from the scan.'
  lines.push(`- ${label(root)}`)
  walk(root.id, 1, new Set([root.id]))
  return lines.join('\n')
}

// --- Components ------------------------------------------------------------------------------

function componentDoc(ctx: Ctx, component: Component, from: string): string {
  const { index, model } = ctx
  const routes = (index.routesOf.get(component.id) ?? [])
    .map((id) => index.routes.get(id))
    .filter((r): r is Route => Boolean(r))
  const renderedBy = [...new Set((index.renderedBy.get(component.id) ?? []).map((r) => r.parentId))]
  const children = component.children.map((ref) =>
    ref.componentId && index.components.has(ref.componentId)
      ? componentLink(ctx, ref.componentId, from)
      : `${code(ref.name)}${ref.module ? ` (${code(ref.module)})` : ''}`,
  )
  const sites = index.requestsByComponent.get(component.id) ?? []
  const navs = model.navigations.filter((n) => n.componentId === component.id)
  const flows = model.flows.filter(
    (f) =>
      f.componentId === component.id ||
      f.steps.some((s) => s.kind === 'interaction' && s.componentId === component.id),
  )

  return doc([
    `# Component ${code(component.name)}`,
    link('← Overview', from, README),
    facts([
      ['File', code(`${component.file}:${component.loc.line}`)],
      ['Kind', `${component.kind}${component.clientBoundary ? ` (${code("'use client'")})` : ''}`],
      ['Used on', routes.map((r) => routeLink(ctx, r, from)).join(', ') || undefined],
      ['Rendered by', renderedBy.map((id) => componentLink(ctx, id, from)).join(', ') || undefined],
      ['Renders', [...new Set(children)].join(', ') || undefined],
    ]),
    '## Props',
    component.propsType ? typeBlock(ctx, component.propsType, from) : 'Takes no props.',
    component.usedTypes.length > 0 && '## Types used',
    component.usedTypes.length > 0 &&
      component.usedTypes.map((id) => `- ${typeLink(ctx, id, from)}`).join('\n'),
    navs.length > 0 && '## Navigation',
    navs.length > 0 && navs.map((n) => `- ${navigationText(ctx, n, from)}`).join('\n'),
    flows.length > 0 && '## Flows',
    flows.length > 0 && flows.map((f) => `- ${flowLink(ctx, f, from)}`).join('\n'),
    '## Requests',
    sites.length === 0 ? 'Sends no requests.' : requestTable(ctx, sites, from),
    ...sites.map((s) => requestSection(ctx, s, from, 3)),
  ])
}

function navigationText(ctx: Ctx, nav: Navigation, from: string): string {
  const target = nav.targetRouteId ? ctx.index.routes.get(nav.targetRouteId) : undefined
  const extra = [
    nav.api === 'next-intl' ? 'next-intl' : '',
    nav.outcome ? `on ${nav.outcome}` : '',
    nav.conditional ? 'conditional' : '',
  ]
    .filter(Boolean)
    .join(', ')
  return `${nav.kind} ${code(urlText(nav.href))}${target ? ` → ${routeLink(ctx, target, from)}` : ''} · ${triggerText(nav.trigger)}${extra ? ` · ${extra}` : ''} · ${code(`${nav.loc.file}:${nav.loc.line}`)}`
}

// --- Requests ---------------------------------------------------------------------------------

function requestTable(ctx: Ctx, sites: RequestSite[], from: string): string {
  return table(
    ['Request', 'Trigger', 'From', 'Status'],
    sites.map((s) => [
      `[${code(requestLabel(s))}](#${anchorId(s.id)})`,
      triggerText(s.trigger),
      ownerText(ctx, s, from),
      statusText(ctx, s),
    ]),
  )
}

/** Everything about one request: where, when, types, type check, captured examples, next hops. */
function requestSection(
  ctx: Ctx,
  site: RequestSite,
  from: string,
  level: number,
  seen = new Set<string>(),
): string {
  const h = '#'.repeat(Math.min(level, MAX_LEVEL))
  const first = site.callStack[0]
  const target = site.targetRouteId ? ctx.index.routes.get(site.targetRouteId) : undefined
  const hook = site.hook ? ` · ${code(`${site.hook.name}${site.hook.key ? `(${site.hook.key})` : ''}`)}` : ''
  const queryKey = site.queryKey ? ` · key ${code(formatQueryKey(site.queryKey))}` : ''
  const url =
    site.url && site.transport !== 'server-action'
      ? `${code(urlText(site.url))}${urlConfidence(site.url.confidence)}`
      : undefined
  const contract = site.contract
    ? `${link(text(site.contract.name), from, POSTMAN, anchorId(site.contract.requestId))}${site.contract.by === 'code' ? ' · matched by name and method, URL from the collection' : ''}`
    : undefined
  const check = ctx.data.verification?.sites[site.id]?.typeCheck
  const next = (site.chain ?? [])
    .map((id) => ctx.index.requests.get(id))
    .filter((s): s is RequestSite => Boolean(s))
  const inner = new Set([...seen, site.id])

  return doc([
    `${h} ${anchor(site.id)}${code(requestLabel(site))}`,
    facts([
      ['Status', statusText(ctx, site)],
      ['From', `${ownerText(ctx, site, from)}${first ? ` · ${code(`${first.file}:${first.line}`)}` : ''}`],
      ['Trigger', triggerText(site.trigger)],
      [
        'Transport',
        `${site.transport}${site.client ? ` (${code(`${site.client.module}#${site.client.name}`)})` : ''}${hook}${queryKey}`,
      ],
      ['URL', url],
      ['Postman', contract],
      [
        site.transport === 'trpc' ? 'tRPC' : 'In procedure',
        site.procedure
          ? `${link(code(site.procedure.path), from, TRPC, anchorId(trpcAnchor(site.procedure.path)))} (${site.procedure.type})`
          : undefined,
      ],
      [
        'GraphQL',
        site.operation
          ? `${link(code(site.operation.name || '(anonymous)'), from, GRAPHQL, anchorId(graphqlAnchor(site.operation)))} (${site.operation.type})`
          : undefined,
      ],
      ['Handled by', target ? routeLink(ctx, target, from) : undefined],
      [
        'Call path',
        site.callStack.length > 1 ? site.callStack.map((f) => code(f.callee)).join(' → ') : undefined,
      ],
    ]),
    site.flags.map((f) => `> ⚠ **${f.kind}**: ${text(f.message)}`).join('\n>\n'),
    site.bodyType && `**Request body**${typeSource(site.bodyType)} ${typeBlock(ctx, site.bodyType, from)}`,
    site.responseType &&
      `**Response**${typeSource(site.responseType)} ${typeBlock(ctx, site.responseType, from)}`,
    check && check.mismatches.length > 0 && typeCheckTable(check),
    examples(ctx, site),
    next.length > 0 && `**Leads to** ${next.map((s) => code(requestLabel(s))).join(', ')}:`,
    ...next.filter((s) => !inner.has(s.id)).map((s) => requestSection(ctx, s, from, level + 1, inner)),
  ]).trimEnd()
}

/** `pattern` and `unknown` as they are; `postman` says where the URL came from. */
function urlConfidence(confidence: NonNullable<RequestSite['url']>['confidence']): string {
  if (confidence === 'exact') return ''
  return confidence === 'postman' ? ' (from Postman)' : ` (${confidence})`
}

/** Marks a type the code doesn't declare, taken from the collection's saved examples. */
function typeSource(ref: TypeRef): string {
  return ref.source === 'postman' ? ' (from Postman examples)' : ''
}

function typeCheckTable(check: SiteTypeCheck): string {
  return `**Type check**: ${check.mismatched} of ${plural(check.checked, 'checked capture')} didn't match.\n\n${table(
    ['Part', 'Field', 'Problem', 'Expected', 'Captured', 'Captures'],
    check.mismatches.map((m) => [
      m.part === 'response' ? 'response' : 'request body',
      code(mismatchField(m.path)),
      m.kind,
      m.expected ? code(m.expected) : '',
      m.actual ? code(m.actual) : '',
      String(m.captures),
    ]),
    ['left', 'left', 'left', 'left', 'left', 'right'],
  )}`
}

/** The newest successful capture and the newest failed one. */
function examples(ctx: Ctx, site: RequestSite): string | undefined {
  const list = ctx.captures.get(site.id) ?? []
  if (list.length === 0) return undefined
  const failed = (c: ExportCapture) => Boolean(c.error) || (c.response?.status ?? 0) >= 400
  const picked = [list.find((c) => !failed(c)), list.find(failed)].filter((c): c is ExportCapture =>
    Boolean(c),
  )
  return picked.map((c) => example(c, list.length)).join('\n\n')
}

function example(c: ExportCapture, total: number): string {
  const status = c.response
    ? `${c.response.status}${c.response.statusText ? ` ${c.response.statusText}` : ''}`
    : `failed${c.error ? `: ${text(c.error)}` : ''}`
  const page = c.pageUrl ? ` · page ${code(pathOf(c.pageUrl))}` : ''
  const stale = c.stale ? ' · taken before the code last changed' : ''
  const lines = [
    `**Captured** ${code(`${c.request.method} ${c.request.url}`)} → ${status} · ${Math.round(c.durationMs)} ms · ${time(c.timestamp)}${page}${stale}${total > 1 ? ` (newest of ${total})` : ''}`,
  ]
  const req = bodyText(c.request.body)
  if (req) lines.push(`Request body:\n\n${req}`)
  const res = c.response ? bodyText(c.response.body) : undefined
  if (res) lines.push(`Response body:\n\n${res}`)
  if (c.redactedPaths.length > 0) lines.push(`Masked: ${c.redactedPaths.map(code).join(', ')}`)
  return lines.join('\n\n')
}

function bodyText(body: CapturedBody): string | undefined {
  switch (body.kind) {
    case 'none':
      return undefined
    case 'json':
      return block('json', cut(JSON.stringify(body.value, null, 2) ?? 'undefined'))
    case 'text':
      return block('text', cut(body.value) + (body.truncated ? '\n… (cut when captured)' : ''))
    case 'form':
      return block('json', cut(JSON.stringify(body.value, null, 2)))
    case 'binary':
      return `(binary${body.contentType ? ` ${code(body.contentType)}` : ''}${body.size !== undefined ? `, ${body.size} bytes` : ''})`
  }
}

function cut(value: string): string {
  let out = value.length > MAX_BODY_CHARS ? value.slice(0, MAX_BODY_CHARS) : value
  const lines = out.split('\n')
  if (lines.length > MAX_BODY_LINES) out = lines.slice(0, MAX_BODY_LINES).join('\n')
  if (out.length < value.length) {
    const more = value.split('\n').length - out.split('\n').length
    out += more > 0 ? `\n… (${plural(more, 'more line')})` : '\n…'
  }
  return out
}

function pathOf(url: string): string {
  try {
    return new URL(url).pathname
  } catch {
    return url.split('?')[0] ?? url
  }
}

/** `Props`, then its resolved shape when that says more, and links to the named types in it. */
function typeBlock(ctx: Ctx, ref: TypeRef, from: string): string {
  const named = ref.shape.kind === 'ref' ? ctx.index.types.get(ref.shape.typeId) : undefined
  if (named) {
    const body = prettyShape(named.shape)
    const head = typeLink(ctx, named.id, from, ref.text)
    return body === ref.text ? head : `${head}\n\n${block('ts', body)}`
  }
  const body = prettyShape(ref.shape)
  const refs = typeRefs(ref.shape).filter((id) => ctx.index.types.has(id))
  const see = refs.length > 0 ? ` (see ${refs.map((id) => typeLink(ctx, id, from)).join(', ')})` : ''
  return body === ref.text ? `${code(ref.text)}${see}` : `${code(ref.text)}${see}\n\n${block('ts', body)}`
}

// --- Flows ------------------------------------------------------------------------------------

function flowDoc(ctx: Ctx, flow: Flow, from: string): string {
  const status = ctx.data.flows?.flows[flow.id]
  const start = flow.routeId ? ctx.index.routes.get(flow.routeId) : undefined
  const recorded = (ctx.data.flows?.recorded ?? []).filter((r) => r.flowId === flow.id)
  const requests = [...flow.steps, ...flow.branches.flatMap((b) => b.steps)]
    .flatMap((s) => (s.kind === 'request' ? [ctx.index.requests.get(s.siteId)] : []))
    .filter((s, i, all): s is RequestSite => Boolean(s) && all.indexOf(s) === i)

  return doc([
    `# Flow: ${text(flow.name)}`,
    link('← Overview', from, README),
    facts([
      [
        'Starts',
        `${componentLink(ctx, flow.componentId, from)}${start ? ` on ${routeLink(ctx, start, from)}` : ''}`,
      ],
      ['Pages', flowPages(ctx, flow, from) || undefined],
      ['Status', flowStatusText(status, Boolean(ctx.data.flows))],
    ]),
    '## Sequence',
    block('mermaid', sequence(ctx, flow)),
    '## Steps',
    stepTable(ctx, flow.steps, from, status?.best?.steps),
    ...flow.branches.flatMap((branch, i) => [
      `### On error after step ${branch.after + 1}${status ? (status.branches[i] ? ' (seen)' : ' (not seen yet)') : ''}`,
      stepTable(ctx, branch.steps, from),
    ]),
    recorded.length > 0 && '## Recorded runs',
    ...recorded.map((r) => recordedSection(ctx, r, from, 3)),
    requests.length > 0 && '## Requests',
    ...requests.map((s) => requestSection(ctx, s, from, 3)),
  ])
}

function flowPages(ctx: Ctx, flow: Flow, from?: string): string {
  return flow.routeIds
    .map((id) => {
      const route = ctx.index.routes.get(id)
      if (!route) return '?'
      return from ? routeLink(ctx, route, from) : code(route.path)
    })
    .join(' → ')
}

function flowStatusText(status: FlowStatus | undefined, hasData: boolean): string {
  if (!hasData) return 'inferred from the code (no captures yet)'
  if (!status || status.status === 'unconfirmed') return 'not walked yet'
  const runs = plural(status.runs, 'run')
  if (status.status === 'confirmed') return `✓ confirmed (${runs})`
  return `partly walked: ${status.best?.steps ?? 0} steps (${runs})`
}

function stepTable(ctx: Ctx, steps: FlowStep[], from: string, done?: number): string {
  return table(
    ['#', 'Step', 'Detail', ...(done !== undefined ? ['Seen'] : [])],
    steps.map((step, i) => [
      String(i + 1),
      stepText(ctx, step, from),
      stepDetail(ctx, step),
      ...(done !== undefined ? [i < done ? '✓' : ''] : []),
    ]),
    ['right', 'left', 'left', 'left'],
  )
}

function stepText(ctx: Ctx, step: FlowStep, from: string): string {
  switch (step.kind) {
    case 'interaction': {
      const route = step.routeId ? ctx.index.routes.get(step.routeId) : undefined
      return `User ${code(step.event)} in ${componentLink(ctx, step.componentId, from)}${route ? ` on ${routeLink(ctx, route, from)}` : ''}`
    }
    case 'request': {
      const site = ctx.index.requests.get(step.siteId)
      if (!site) return `Request ${code(step.siteId)}`
      return `${step.onLoad ? 'Page loads: ' : ''}[${code(requestLabel(site))}](#${anchorId(site.id)})`
    }
    case 'navigate': {
      const nav = ctx.index.navigations.get(step.navigationId)
      const route = step.routeId ? ctx.index.routes.get(step.routeId) : undefined
      const where = route ? routeLink(ctx, route, from) : nav ? code(urlText(nav.href)) : '?'
      return `${nav?.kind ?? 'navigate'} → ${where}`
    }
    case 'query-update': {
      const link = ctx.index.queryLinks.get(step.linkId)
      if (!link) return `Cache update ${code(step.linkId)}`
      return `${code(link.method)} ${code(queryLinkTarget(link))}`
    }
  }
}

function stepDetail(ctx: Ctx, step: FlowStep): string {
  switch (step.kind) {
    case 'interaction':
      return code(`${step.loc.file}:${step.loc.line}`)
    case 'request': {
      const site = ctx.index.requests.get(step.siteId)
      if (!site) return ''
      const parts = [
        site.bodyType ? `body ${code(site.bodyType.text)}` : '',
        site.responseType ? `response ${code(site.responseType.text)}` : '',
        statusText(ctx, site),
      ]
      return parts.filter(Boolean).join(' · ')
    }
    case 'navigate': {
      const nav = ctx.index.navigations.get(step.navigationId)
      return nav
        ? `${nav.outcome ? `on ${nav.outcome} · ` : ''}${code(`${nav.loc.file}:${nav.loc.line}`)}`
        : ''
    }
    case 'query-update': {
      const link = ctx.index.queryLinks.get(step.linkId)
      if (!link) return ''
      const hits = link.targetSiteIds.map((id) => ctx.index.requests.get(id)).filter((s) => !!s)
      const refetch =
        hits.length > 0
          ? `${queryLinkVerb(link.kind)} ${hits.map((s) => code(requestLabel(s))).join(', ')} · `
          : ''
      return `${refetch}${code(`${link.loc.file}:${link.loc.line}`)}`
    }
  }
}

/** Mermaid sequence: the user, each page, the app's server and external APIs. */
function sequence(ctx: Ctx, flow: Flow): string {
  const participants: { id: string; label: string; actor?: boolean }[] = [
    { id: 'U', label: 'User', actor: true },
  ]
  const ids = new Map<string, string>()
  const participant = (key: string, label: string) => {
    let id = ids.get(key)
    if (!id) {
      id = `P${ids.size}`
      ids.set(key, id)
      participants.push({ id, label })
    }
    return id
  }
  const pageOf = (routeId: string | undefined) => {
    const route = routeId ? ctx.index.routes.get(routeId) : undefined
    return participant(`route:${routeId ?? '?'}`, route?.path ?? 'page')
  }
  const lines: string[] = []
  let current = pageOf(flow.routeId ?? flow.routeIds[0])

  const emit = (steps: FlowStep[], indent: string, branchesAfter?: (i: number) => void) => {
    steps.forEach((step, i) => {
      switch (step.kind) {
        case 'interaction': {
          current = pageOf(step.routeId ?? undefined)
          const name = ctx.index.components.get(step.componentId)?.name ?? '?'
          lines.push(`${indent}U->>${current}: ${mermaid(`${step.event} (${name})`)}`)
          break
        }
        case 'request': {
          const site = ctx.index.requests.get(step.siteId)
          if (!site) break
          const server = destination(ctx, site, participant)
          const label = `${step.onLoad ? 'on load: ' : ''}${diagramLabel(site)}`
          lines.push(`${indent}${current}->>${server}: ${mermaid(label)}`)
          for (const hop of site.chain ?? []) {
            const next = ctx.index.requests.get(hop)
            if (!next) continue
            const to = destination(ctx, next, participant)
            lines.push(`${indent}${server}->>${to}: ${mermaid(diagramLabel(next))}`)
            lines.push(`${indent}${to}-->>${server}: ${mermaid(responseLabel(ctx, next))}`)
          }
          lines.push(`${indent}${server}-->>${current}: ${mermaid(responseLabel(ctx, site))}`)
          break
        }
        case 'navigate': {
          const nav = ctx.index.navigations.get(step.navigationId)
          const to = step.routeId ? pageOf(step.routeId) : participant('nav:?', nav ? urlText(nav.href) : '?')
          lines.push(`${indent}${current}->>${to}: ${mermaid(nav?.kind ?? 'navigate')}`)
          current = to
          break
        }
        case 'query-update': {
          const link = ctx.index.queryLinks.get(step.linkId)
          const key = link ? queryLinkTarget(link) : 'all queries'
          lines.push(`${indent}Note over ${current}: ${mermaid(`${link?.method ?? 'cache update'} ${key}`)}`)
          break
        }
      }
      branchesAfter?.(i)
    })
  }
  emit(flow.steps, '  ', (i) => {
    for (const branch of flow.branches.filter((b) => b.after === i)) {
      const back = current
      lines.push('  opt on error')
      emit(branch.steps, '    ')
      lines.push('  end')
      current = back
    }
  })
  const head = participants.map(
    (p) => `  ${p.actor ? 'actor' : 'participant'} ${p.id} as ${mermaid(p.label)}`,
  )
  return ['sequenceDiagram', ...head, ...lines].join('\n')
}

/** Server actions and route handlers run on the app's server; anything else is an external API. */
function destination(
  ctx: Ctx,
  site: RequestSite,
  participant: (key: string, label: string) => string,
): string {
  if (site.transport === 'server-action') return participant('server', 'Next.js server')
  if (site.targetRouteId) {
    const route = ctx.index.routes.get(site.targetRouteId)
    return participant(`handler:${site.targetRouteId}`, `${route?.path ?? 'route handler'} (handler)`)
  }
  const base = site.url?.baseEnv ?? site.url?.base
  return participant(`api:${base ?? ''}`, base ? `API (${base})` : 'API')
}

/** Short request text for diagrams: the host is the participant, so only method and path. */
function diagramLabel(site: RequestSite): string {
  if (site.transport === 'server-action') return `${site.serverAction?.name ?? '?'}()`
  const url = site.url
  const path = url?.path ? `${url.path}${url.query ? `?${url.query}` : ''}` : (url?.text ?? '?')
  return `${site.method ?? '?'} ${path}`
}

function responseLabel(ctx: Ctx, site: RequestSite): string {
  const example = ctx.captures.get(site.id)?.[0]
  const status = example?.response ? `${example.response.status} ` : ''
  return `${status}${site.responseType?.text ?? 'response'}`
}

// --- Recorded flows ------------------------------------------------------------------------------

function recordedDoc(ctx: Ctx, recorded: RecordedFlow[]): string {
  const from = RECORDED
  return doc([
    '# Recorded flows',
    link('← Overview', from, README),
    'Named recordings you made in the dashboard, and walks that went somewhere the code did not predict (variants).',
    ...recorded.map((r) => recordedSection(ctx, r, from, 2)),
  ])
}

function recordedSection(ctx: Ctx, flow: RecordedFlow, from: string, level: number): string {
  const h = '#'.repeat(level)
  const inferred = flow.flowId ? ctx.index.flows.get(flow.flowId) : undefined
  return doc([
    `${h} ${anchor(flow.id)}${text(flow.name)}`,
    facts([
      ['Kind', flow.kind === 'named' ? 'named recording' : 'variant'],
      ['Follows', inferred ? flowLink(ctx, inferred, from) : undefined],
      ['Went elsewhere after step', flow.divergedAt !== undefined ? String(flow.divergedAt + 1) : undefined],
      ['Recorded', `${time(flow.startedAt)}${flow.endedAt ? ` – ${time(flow.endedAt)}` : ''}`],
    ]),
    flow.steps.length === 0
      ? 'No steps were recorded.'
      : table(
          ['#', 'Step'],
          flow.steps.map((s, i) => [String(i + 1), recordedStep(ctx, s, from)]),
          ['right', 'left'],
        ),
  ]).trimEnd()
}

function recordedStep(ctx: Ctx, step: RecordedStep, from: string): string {
  const routeText = (id: string | undefined) => {
    const route = id ? ctx.index.routes.get(id) : undefined
    return route ? ` on ${routeLink(ctx, route, from)}` : ''
  }
  switch (step.kind) {
    case 'interaction':
      return `User ${code(step.type)}${step.component ? ` in ${code(step.component)}` : ''} on ${text(step.target)}${routeText(step.routeId)}`
    case 'request': {
      const site = step.siteId ? ctx.index.requests.get(step.siteId) : undefined
      const status = step.status !== undefined ? ` → ${step.status}` : ''
      return `${code(`${step.method} ${step.path}`)}${status}${site ? ` (${siteLink(ctx, site, from)})` : ''}`
    }
    case 'navigate':
      return `${step.how} → ${code(step.path)}${routeText(step.routeId)}`
  }
}

// --- Types ------------------------------------------------------------------------------------

function typesDoc(ctx: Ctx): string {
  const from = TYPES
  const { index } = ctx
  const sections = ctx.model.types.map((type) => {
    const usage = index.typeUsage.get(type.id)
    const used: string[] = []
    if (usage) {
      for (const id of usage.props) used.push(`props of ${componentLink(ctx, id, from)}`)
      for (const id of usage.usedBy) used.push(`used in ${componentLink(ctx, id, from)}`)
      for (const id of usage.requests) {
        const site = index.requests.get(id)
        if (site) used.push(`request ${siteLink(ctx, site, from)}`)
      }
      for (const id of usage.inTypes) used.push(`in ${typeLink(ctx, id, from)}`)
    }
    return doc([
      `## ${anchor(type.id)}${text(type.name)}`,
      `${type.declarationKind} · ${code(`${type.definedAt.file}:${type.definedAt.line}`)}`,
      block('ts', declaration(type)),
      used.length > 0 ? `Used by: ${used.join(', ')}.` : 'Not used by any component or request directly.',
    ]).trimEnd()
  })
  return doc([
    '# Types',
    link('← Overview', from, README),
    ctx.model.types.length === 0
      ? 'No named project types are used by components or requests.'
      : `${plural(ctx.model.types.length, 'named type')}, fully resolved.`,
    ...sections,
  ])
}

// --- Issues -----------------------------------------------------------------------------------

const NOTE_GROUPS: { title: string; kinds: ScanNote['kind'][]; hint: string }[] = [
  {
    title: 'Type mismatches',
    kinds: ['type-mismatch'],
    hint: 'Captured data does not fit the declared types.',
  },
  {
    title: 'Needs a re-check',
    kinds: ['needs-recheck'],
    hint: 'The code changed after every capture. Use the app again to re-check.',
  },
  {
    title: 'Requests the scan could not fully resolve',
    kinds: ['request'],
    hint: 'Dynamic URLs, unknown methods or response types. Live capture fills these in.',
  },
  {
    title: 'Components and types the scan could not resolve',
    kinds: ['unresolved-component', 'unresolved-type', 'missing-page-component'],
    hint: '',
  },
]

function issueTotal(ctx: Ctx): number {
  const counts = ctx.data.verification?.counts
  return (
    ctx.index.notes.length + (counts ? counts.unmatched + counts.ambiguous : 0) + unconfirmedFlows(ctx).length
  )
}

function unconfirmedFlows(ctx: Ctx): Flow[] {
  const flows = ctx.data.flows
  if (!flows) return []
  return ctx.model.flows.filter((f) => flows.flows[f.id]?.status !== 'confirmed')
}

function issuesDoc(ctx: Ctx): string {
  const from = ISSUES
  const sections: (string | false)[] = [`# Issues`, link('← Overview', from, README)]
  const total = issueTotal(ctx)
  sections.push(total === 0 ? 'Nothing to check. 🎉' : `${plural(total, 'open item')}.`)

  for (const group of NOTE_GROUPS) {
    const notes = ctx.index.notes.filter((n) => group.kinds.includes(n.kind))
    if (notes.length === 0) continue
    sections.push(
      `## ${group.title} (${notes.length})`,
      group.hint,
      notes.map((n) => `- ${noteText(ctx, n, from)}`).join('\n'),
    )
  }

  const unmatched = ctx.data.captures.filter((c) => c.match?.status !== 'matched')
  const counts = ctx.data.verification?.counts
  if (counts && counts.unmatched + counts.ambiguous > 0) {
    const shown =
      unmatched.length < counts.unmatched + counts.ambiguous
        ? ` The newest ${unmatched.length} are listed.`
        : ''
    sections.push(
      `## Captures without a request site (${counts.unmatched + counts.ambiguous})`,
      `No scanned request site fits these (unmatched), or several fit equally well (ambiguous). Unmatched requests usually point at code the scanner missed. Assign them in the dashboard's Live screen.${shown}`,
      table(
        ['Time', 'Request', 'Status', 'Page', 'Match'],
        [...unmatched]
          .reverse()
          .map((c) => [
            time(c.timestamp),
            code(`${c.request.method} ${c.request.url}`),
            c.response ? String(c.response.status) : 'failed',
            c.pageUrl ? code(pathOf(c.pageUrl)) : c.origin,
            c.match?.status ?? 'unmatched',
          ]),
      ),
    )
  }

  const flows = unconfirmedFlows(ctx)
  if (flows.length > 0) {
    sections.push(
      `## Flows not confirmed (${flows.length})`,
      'Inferred from the code but not walked end to end in a recorded session yet.',
      flows
        .map((f) => `- ${flowLink(ctx, f, from)}: ${flowStatusText(ctx.data.flows?.flows[f.id], true)}`)
        .join('\n'),
    )
  }
  return doc(sections)
}

function noteText(ctx: Ctx, note: ScanNote, from: string): string {
  const where = code(`${note.file}${note.line ? `:${note.line}` : ''}`)
  let target = ''
  let message = note.message
  if (note.requestId) {
    const site = ctx.index.requests.get(note.requestId)
    if (site) {
      target = siteLink(ctx, site, from)
      // The message starts with the request label, which the link already shows.
      const prefix = `${requestLabel(site)}: `
      if (message.startsWith(prefix)) message = message.slice(prefix.length)
    }
  } else if (note.typeId) {
    target = typeLink(ctx, note.typeId, from)
  } else if (note.componentId) {
    target = componentLink(ctx, note.componentId, from)
  } else if (note.routeId) {
    const route = ctx.index.routes.get(note.routeId)
    if (route) target = routeLink(ctx, route, from)
  }
  return `${target ? `${target}: ` : ''}${text(message)} (${where})`
}

// --- Links and labels --------------------------------------------------------------------------

function routeLink(ctx: Ctx, route: Route, from: string): string {
  const file = ctx.names.route(route.id)
  const label = code(route.kind === 'page' ? route.path : route.path)
  return file ? link(label, from, file) : label
}

function componentLink(ctx: Ctx, id: string, from: string): string {
  const c = ctx.index.components.get(id)
  const file = ctx.names.component(id)
  const label = code(c?.name ?? id)
  return file ? link(label, from, file) : label
}

function flowLink(ctx: Ctx, flow: Flow, from: string): string {
  const file = ctx.names.flow(flow.id)
  return file ? link(text(flow.name), from, file) : text(flow.name)
}

function typeLink(ctx: Ctx, id: string, from: string, label?: string): string {
  const type = ctx.index.types.get(id)
  return link(code(label ?? type?.name ?? id), from, TYPES, anchorId(id))
}

/** Link to where a request is documented: its component, its route handler, or its caller. */
function siteLink(ctx: Ctx, site: RequestSite, from: string): string {
  const home = siteHome(ctx, site)
  const label = code(requestLabel(site))
  return home ? link(label, from, home, anchorId(site.id)) : label
}

function siteHome(ctx: Ctx, site: RequestSite, seen = new Set<string>()): string | undefined {
  if (site.origin === 'component' && site.componentId) return ctx.names.component(site.componentId)
  if (site.origin === 'route-handler' && site.routeId) return ctx.names.route(site.routeId)
  if (site.origin === 'middleware') return MIDDLEWARE
  const caller = ctx.callers.get(site.id)
  if (!caller || seen.has(caller.id)) return undefined
  return siteHome(ctx, caller, new Set([...seen, site.id]))
}

/** Who sends it: the component, the route handler, or the server action. */
function ownerText(ctx: Ctx, site: RequestSite, from: string): string {
  if (site.origin === 'component' && site.componentId) return componentLink(ctx, site.componentId, from)
  if (site.origin === 'route-handler' && site.routeId) {
    const route = ctx.index.routes.get(site.routeId)
    return `${site.handlerMethod ?? '?'} ${route ? routeLink(ctx, route, from) : '?'}`
  }
  if (site.origin === 'middleware')
    return from === MIDDLEWARE ? 'middleware' : link('middleware', from, MIDDLEWARE)
  return `server action ${code(site.serverAction?.name ?? '?')}`
}

function statusText(ctx: Ctx, site: RequestSite): string {
  const n = ctx.data.verification?.sites[site.id]?.captures ?? 0
  const captures = n > 0 ? ` (${plural(n, 'capture')})` : ''
  switch (site.status) {
    case 'verified':
      return `✓ verified${captures}`
    case 'mismatch':
      return `✗ type mismatch${captures}`
    case 'needs-recheck':
      return `↻ needs re-check${captures}`
    case 'inferred':
      return 'inferred'
  }
}

function statusCounts(sites: RequestSite[]): string {
  if (sites.length === 0) return '—'
  const n = (status: RequestSite['status']) => sites.filter((s) => s.status === status).length
  const parts = [
    n('verified') > 0 && `✓ ${n('verified')} verified`,
    n('mismatch') > 0 && `✗ ${n('mismatch')} mismatch`,
    n('needs-recheck') > 0 && `↻ ${n('needs-recheck')} re-check`,
    n('inferred') > 0 && `${n('inferred')} inferred`,
  ]
  return parts.filter(Boolean).join(', ')
}
