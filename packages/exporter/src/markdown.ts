/** Generated files: path (forward slashes, relative to the output folder) → content. */
export type ExportFiles = Record<string, string>

/** Lines of a body shown in an example before it is cut. */
const MAX_BODY_LINES = 40
const MAX_BODY_CHARS = 4000
/** Deepest heading used for nested request hops. */
const MAX_LEVEL = 6

interface Ctx {
  data: ExportData
  model: AppModel
  index: ModelIndex
  names: DocNames
  /** Site id → its captures, newest first. */
  captures: Map<string, ExportCapture[]>
  /** Site id → the site whose `chain` leads to it. */
  callers: Map<string, RequestSite>
}

export function renderMarkdown(data: ExportData): ExportFiles {
  const model = data.model
  const index = buildIndex(model)
  const captures = new Map<string, ExportCapture[]>()
  for (let i = data.captures.length - 1; i >= 0; i--) {
    const c = data.captures[i]
    const siteId = c?.match?.status === 'matched' ? c.match.siteId : undefined
    if (!c || !siteId) continue
    const list = captures.get(siteId)
    if (list) list.push(c)
    else captures.set(siteId, [c])
  }
  const callers = new Map<string, RequestSite>()
  for (const site of model.requests) {
    for (const id of site.chain ?? []) if (!callers.has(id)) callers.set(id, site)
  }
  const ctx: Ctx = { data, model, index, names: docNames(model), captures, callers }

  const files: ExportFiles = {}
  files[README] = readme(ctx)
  for (const route of model.routes) {
    const file = ctx.names.route(route.id)
    if (file) files[file] = route.kind === 'page' ? pageDoc(ctx, route, file) : handlerDoc(ctx, route, file)
  }
  for (const component of model.components) {
    const file = ctx.names.component(component.id)
    if (file) files[file] = componentDoc(ctx, component, file)
  }
  for (const flow of model.flows) {
    const file = ctx.names.flow(flow.id)
    if (file) files[file] = flowDoc(ctx, flow, file)
  }
  const recorded = data.flows?.recorded ?? []
  if (recorded.length > 0) files[RECORDED] = recordedDoc(ctx, recorded)
  if (model.middleware) files[MIDDLEWARE] = middlewareDoc(ctx)
  if (model.postman) files[POSTMAN] = postmanDoc(ctx, model.postman)
  if (model.trpc) files[TRPC] = trpcDoc(ctx, model.trpc)
  if (model.graphql) files[GRAPHQL] = graphqlDoc(ctx, model.graphql)
  files[TYPES] = typesDoc(ctx)
  files[ISSUES] = issuesDoc(ctx)
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
}

// --- README -------------------------------------------------------------------------------

function readme(ctx: Ctx): string {
  const { model, data, index } = ctx
  const from = README
  const pages = model.routes.filter((r) => r.kind === 'page')
  const handlers = model.routes.filter((r) => r.kind === 'route-handler')
  const project = model.project
  const source = `${code(project.appDir)}${project.nextVersion ? ` (Next.js ${project.nextVersion})` : ''}`

  const intro = [
    `Generated by flow-checker${data.toolVersion ? ` v${data.toolVersion}` : ''} on ${time(data.generatedAt)} from a scan of ${source}.`,
    data.captureCounts.total > 0
      ? data.redacted
        ? '> Captured requests in these docs are redacted: passwords, tokens and other sensitive values are masked.'
        : '> ⚠ Raw export: captured requests are **not** redacted. Do not share these docs.'
      : '',
  ]

  const counts = table(
    ['', 'Count'],
    [
      ['Pages', String(pages.length)],
      ['Route handlers', String(handlers.length)],
      ['Components', String(model.components.length)],
      ['Requests', String(model.requests.length)],
      ['Flows', String(model.flows.length)],
      ['Types', String(model.types.length)],
    ],
    ['left', 'right'],
  )

  const issueCount = issueTotal(ctx)
  const issues = `${issueCount === 0 ? 'No open issues' : link(plural(issueCount, 'open issue'), from, ISSUES)}. ${link('All types', from, TYPES)}.`

  const sections = [
    `# ${text(data.projectName)}: flow map`,
    intro.filter(Boolean).join('\n\n'),
    '## Summary',
    counts,
    '## Verification',
    verificationSummary(ctx),
    issues,
    '## Route map',
    routeMap(ctx),
  ]

  if (pages.length > 0) {
    sections.push(
      '## Pages',
      table(
        ['Page', 'File', 'Requests', 'Status'],
        pages.map((route) => {
          const sites = routeSites(ctx, route)
          return [routeLink(ctx, route, from), code(route.file), String(sites.length), statusCounts(sites)]
        }),
      ),
    )
  }
  if (handlers.length > 0) {
    sections.push(
      '## Route handlers',
      table(
        ['Route', 'Methods', 'File', 'Requests it sends'],
        handlers.map((route) => [
          routeLink(ctx, route, from),
          (route.methods ?? []).join(', ') || '?',
          code(route.file),
          String(index.handlerRequests.get(route.id)?.length ?? 0),
        ]),
      ),
    )
  }
  const mw = model.middleware
  if (mw) {
    const conditional = mw.routes.filter((r) => r.conditional).length
    const redirects = model.navigations.filter((n) => n.origin === 'middleware').length
    const parts = [
      `runs on ${plural(mw.routes.length, 'route')}${conditional > 0 ? ` (${conditional} only for some requests)` : ''}`,
      plural(redirects, 'redirect'),
      plural(mw.rewrites.length, 'rewrite'),
      plural(index.middlewareRequests.length, 'request'),
    ]
    sections.push('## Middleware', `${link(code(mw.file), from, MIDDLEWARE)}: ${parts.join(', ')}.`)
  }
  if (model.postman) {
    sections.push(
      '## Postman collection',
      `${link(text(model.postman.collection.name), from, POSTMAN)}: ${postmanCounts(ctx, model.postman)}.`,
    )
  }
  if (model.trpc) {
    sections.push('## tRPC', `${link(code(model.trpc.endpoint), from, TRPC)}: ${trpcCounts(model.trpc)}.`)
  }
  if (model.graphql) {
    const endpoint = model.graphql.endpoint ? urlText(model.graphql.endpoint) : 'GraphQL'
    sections.push('## GraphQL', `${link(code(endpoint), from, GRAPHQL)}: ${graphqlCounts(model.graphql)}.`)
  }
  if (model.flows.length > 0) {
    sections.push(
      '## Flows',
      table(
        ['Flow', 'Pages', 'Status'],
        model.flows.map((flow) => [
          flowLink(ctx, flow, from),
          flowPages(ctx, flow),
          flowStatusText(ctx.data.flows?.flows[flow.id], Boolean(ctx.data.flows)),
        ]),
      ),
    )
    if ((data.flows?.recorded.length ?? 0) > 0) {
      sections.push(link(`Recorded flows (${data.flows?.recorded.length})`, from, RECORDED))
    }
  }
  if (model.components.length > 0) {
    sections.push(
      '## Components',
      table(
        ['Component', 'Kind', 'File', 'Requests'],
        model.components.map((c) => [
          componentLink(ctx, c.id, from),
          c.kind,
          code(`${c.file}:${c.loc.line}`),
          String(index.requestsByComponent.get(c.id)?.length ?? 0),
        ]),
      ),
    )
  }
  return doc(sections)
}

function verificationSummary(ctx: Ctx): string {
  const { model, data } = ctx
  const total = model.requests.length
  if (data.captureCounts.total === 0) {
    return total === 0
      ? 'No requests found.'
      : 'No captures yet: every request is inferred from the code. Run `flow-checker`, use the app, then export again to verify them.'
  }
  const verified = model.requests.filter(isVerified).length
  const mismatch = model.requests.filter((s) => s.status === 'mismatch').length
  const recheck = model.requests.filter((s) => s.status === 'needs-recheck').length
  const percent = total === 0 ? 0 : Math.round((verified / total) * 100)
  const counts = data.verification?.counts
  const lines = [`- **${verified} of ${plural(total, 'request')} verified** by live capture (${percent}%).`]
  if (mismatch > 0 || recheck > 0) {
    lines.push(
      `- ${plural(mismatch, 'request')} with a type mismatch, ${plural(recheck, 'request')} to re-check after a code change.`,
    )
  }
  if (counts) {
    const shown =
      data.captureCounts.included < data.captureCounts.total
        ? ` (the newest ${data.captureCounts.included} are included)`
        : ''
    lines.push(
      `- ${plural(data.captureCounts.total, 'capture')}${shown}: ${counts.matched} matched, ${counts.ambiguous} ambiguous, ${counts.unmatched} unmatched.`,
    )
  }
  if (data.flows && model.flows.length > 0) {
    const statuses = model.flows.map((f) => data.flows?.flows[f.id]?.status ?? 'unconfirmed')
    const n = (s: string) => statuses.filter((x) => x === s).length
    lines.push(
      `- Flows: ${n('confirmed')} confirmed, ${n('partial')} partly walked, ${n('unconfirmed')} not walked yet.`,
    )
  }
  return lines.join('\n')
}

/** Pages and route handlers with navigation edges (solid) and calls to handlers (dotted). */
function routeMap(ctx: Ctx): string {
  const { model, index } = ctx
  if (model.routes.length === 0) return 'No routes found.'
  const ids = new Map(model.routes.map((r, i) => [r.id, `r${i}`]))
  const lines = ['graph LR']
  for (const route of model.routes) {
    const label = route.kind === 'page' ? route.path : `${(route.methods ?? []).join(', ')} ${route.path}`
    const [open, close] = route.kind === 'page' ? ['["', '"]'] : ['[/"', '"/]']
    lines.push(`  ${ids.get(route.id)}${open}${mermaid(label.trim())}${close}`)
  }
  for (const edge of index.navEdges) {
    const kinds = edge.kinds.join(', ')
    lines.push(`  ${ids.get(edge.source)} -->|${mermaid(kinds)}| ${ids.get(edge.target)}`)
  }
  const calls = new Set<string>()
  for (const site of model.requests) {
    if (!site.targetRouteId || !site.componentId) continue
    for (const routeId of index.routesOf.get(site.componentId) ?? []) {
      const route = index.routes.get(routeId)
      if (route?.kind !== 'page') continue
      const key = `  ${ids.get(routeId)} -.-> ${ids.get(site.targetRouteId)}`
      if (!calls.has(key)) {
        calls.add(key)
        lines.push(key)
      }
    }
  }
  const classes = new Map<string, string[]>()
  for (const route of model.routes) {
    const status = routeStatus(routeSites(ctx, route))
    const list = classes.get(status) ?? []
    list.push(ids.get(route.id) ?? '')
    classes.set(status, list)
  }
  const styles: Record<string, string> = {
    verified: 'fill:#dcfce7,stroke:#16a34a',
    mismatch: 'fill:#fee2e2,stroke:#dc2626',
    recheck: 'fill:#fef3c7,stroke:#d97706',
    inferred: 'fill:#f1f5f9,stroke:#64748b',
  }
  for (const [status, list] of classes) {
    lines.push(`  classDef ${status} ${styles[status]}`)
    lines.push(`  class ${list.join(',')} ${status}`)
  }
  const legend =
    ctx.data.captureCounts.total > 0
      ? 'Green: every request verified. Red: a type mismatch. Amber: needs a re-check. Grey: not verified yet. Dotted: calls a route handler.'
      : 'Dotted arrows: the page calls a route handler.'
  return `${block('mermaid', lines.join('\n'))}\n\n${legend}`
}

function routeStatus(sites: RequestSite[]): 'verified' | 'mismatch' | 'recheck' | 'inferred' {
  if (sites.some((s) => s.status === 'mismatch')) return 'mismatch'
  if (sites.some((s) => s.status === 'needs-recheck')) return 'recheck'
  if (sites.length > 0 && sites.every(isVerified)) return 'verified'
  return 'inferred'
}

// --- Pages and route handlers ----------------------------------------------------------------

/** Requests a page sends (from its components and layouts), or a handler sends. */
function routeSites(ctx: Ctx, route: Route): RequestSite[] {
  if (route.kind === 'route-handler') return ctx.index.handlerRequests.get(route.id) ?? []
  return ctx.model.requests.filter(
    (s) => s.componentId && (ctx.index.routesOf.get(s.componentId) ?? []).includes(route.id),
  )
}

function pageDoc(ctx: Ctx, route: Route, from: string): string {
  const { index } = ctx
  const sites = routeSites(ctx, route)
  const layouts = route.layoutChain.map((l) =>
    l.componentId ? `${componentLink(ctx, l.componentId, from)} (${code(l.file)})` : code(l.file),
  )
  const flows = index.flowsByRoute.get(route.id) ?? []
  const navs = ctx.index.navEdges.filter((e) => e.source === route.id || e.target === route.id)

  return doc([
    `# Page ${code(route.path)}`,
    link('← Overview', from, README),
    facts([
      ['File', code(route.file)],
      ['Slot', route.slot ? code(`@${route.slot}`) : undefined],
      [
        'Intercepts',
        route.intercepting
          ? `${code(route.intercepting.from)} (${code(route.intercepting.marker)})`
          : undefined,
      ],
      ['Layouts', layouts.join(' → ') || undefined],
      ['Status', sites.length > 0 ? statusCounts(sites) : undefined],
    ]),
    '## Component tree',
    route.componentId
      ? componentTree(ctx, route.componentId, from)
      : 'No default-export component was found.',
    navs.length > 0 && '## Navigation',
    navs.length > 0 &&
      navs
        .map((e) => {
          const out = e.source === route.id
          const other = index.routes.get(out ? e.target : e.source)
          const target = other ? routeLink(ctx, other, from) : '?'
          return `- ${out ? 'To' : 'From'} ${target} (${e.kinds.join(', ')})`
        })
        .join('\n'),
    flows.length > 0 && '## Flows',
    flows.length > 0 && flows.map((f) => `- ${flowLink(ctx, f, from)}`).join('\n'),
    ...routeMiddleware(ctx, route, from),
    '## Requests',
    sites.length === 0 ? 'This page sends no requests the scan found.' : requestTable(ctx, sites, from),
    ...sites.map((s) => requestSection(ctx, s, from, 3)),
  ])
}

function handlerDoc(ctx: Ctx, route: Route, from: string): string {
  const sends = ctx.index.handlerRequests.get(route.id) ?? []
  const callers = ctx.index.handlerCallers.get(route.id) ?? []
  return doc([
    `# Route handler ${code(route.path)}`,
    link('← Overview', from, README),
    facts([
      ['File', code(route.file)],
      ['Methods', (route.methods ?? []).join(', ') || undefined],
    ]),
    ...routeMiddleware(ctx, route, from),
    '## Called by',
    callers.length === 0
      ? 'No request in the app calls it (it may be called from outside).'
      : table(
          ['Request', 'From', 'Status'],
          callers.map((s) => [siteLink(ctx, s, from), ownerText(ctx, s, from), statusText(ctx, s)]),
        ),
    '## Requests it sends',
    sends.length === 0 ? 'None found.' : requestTable(ctx, sends, from),
    ...sends.map((s) => requestSection(ctx, s, from, 3)),
  ])
}

// --- Middleware (M14) -----------------------------------------------------------------------

/** On a page or handler doc: whether the middleware runs, its redirects away and rewrites to it. */
function routeMiddleware(ctx: Ctx, route: Route, from: string): (string | false)[] {
  const mw = ctx.model.middleware
  if (!mw) return []
  const runs = ctx.index.middlewareRoutes.get(route.id)
  const redirects = ctx.index.middlewareRedirects.get(route.id) ?? []
  const rewrites = ctx.index.rewritesTo.get(route.id) ?? []
  if (!runs && rewrites.length === 0) return []
  const file = link(code(mw.file), from, MIDDLEWARE)
  const intro = runs
    ? runs.conditional
      ? `${file} runs here only for some requests (${conditionalReason(mw)}).`
      : `${file} runs before every request to this route.`
    : `${file} rewrites other paths to this route.`
  const lines: string[] = []
  for (const nav of redirects) {
    const target = nav.targetRouteId ? ctx.index.routes.get(nav.targetRouteId) : undefined
    const to = target ? routeLink(ctx, target, from) : code(urlText(nav.href))
    lines.push(`- Redirects to ${to}${nav.condition ? ` if ${code(nav.condition)}` : ''}`)
  }
  for (const rw of rewrites) {
    lines.push(
      `- Answers ${code(rewriteFrom(rw.from))} (rewrite)${rw.condition ? ` if ${code(rw.condition)}` : ''}`,
    )
  }
  return ['## Middleware', intro, lines.length > 0 && lines.join('\n')]
}

function conditionalReason(mw: NonNullable<AppModel['middleware']>): string {
  if (mw.matcherText !== undefined) return 'the matcher could not be read'
  return 'see the matcher'
}

function rewriteFrom(from: { kind: 'prefix' | 'exact'; path: string } | undefined): string {
  return from ? `${from.path}${from.kind === 'prefix' ? '/*' : ''}` : 'every path it runs on'
}

function middlewareMatcherText(m: MiddlewareMatcher): string {
  const cond = (word: string, list: MatcherCondition[] | undefined) =>
    list?.map((c) => `${word} ${c.type} ${c.key}${c.value !== undefined ? `=${c.value}` : ''}`) ?? []
  const extra = [...cond('has', m.has), ...cond('missing', m.missing)]
  return `${code(m.source)}${extra.length > 0 ? ` (${extra.join(', ')})` : ''}`
}

function middlewareDoc(ctx: Ctx): string {
  const { model, index } = ctx
  const mw = model.middleware
  if (!mw) return ''
  const from = MIDDLEWARE
  const redirects = model.navigations.filter((n) => n.origin === 'middleware')
  const routeOf = (id: string | undefined) => (id ? index.routes.get(id) : undefined)
  const routeText = (id: string | undefined) => {
    const route = routeOf(id)
    return route ? routeLink(ctx, route, from) : '—'
  }
  const sites = index.middlewareRequests
  return doc([
    `# Middleware ${code(mw.file)}`,
    link('← Overview', from, README),
    facts([
      ['File', code(`${mw.loc.file}:${mw.loc.line}`)],
      ['Convention', mw.convention === 'proxy' ? '`proxy` (Next.js 16+)' : '`middleware`'],
      ['Export', mw.exportName ? code(mw.exportName) : undefined],
      ['Made with', mw.factory ? `${code(mw.factory.name)} from ${code(mw.factory.module)}` : undefined],
      [
        'Matcher',
        mw.matcherText !== undefined
          ? `could not be read: ${code(mw.matcherText)}`
          : mw.matchers.length === 0
            ? 'every request'
            : mw.matchers.map(middlewareMatcherText).join(', '),
      ],
      [
        'Locales',
        mw.i18n
          ? `${mw.i18n.locales.map(code).join(', ')}${mw.i18n.defaultLocale ? ` (default ${code(mw.i18n.defaultLocale)})` : ''}`
          : undefined,
      ],
    ]),
    '## Runs on',
    mw.routes.length === 0
      ? 'No route in the app matches.'
      : table(
          ['Route', 'Kind', 'When'],
          mw.routes.map((r) => [
            routeText(r.routeId),
            routeOf(r.routeId)?.kind === 'route-handler' ? 'route handler' : 'page',
            r.conditional ? 'some requests' : 'every request',
          ]),
        ),
    redirects.length > 0 && '## Redirects',
    redirects.length > 0 &&
      table(
        ['To', 'From', 'If', 'Source'],
        redirects.map((nav) => [
          nav.targetRouteId ? routeText(nav.targetRouteId) : code(urlText(nav.href)),
          // The pages it runs on, or the path it checks when no page has that path.
          (nav.sourceRouteIds ?? []).map((id) => routeText(id)).join(', ') ||
            (nav.from ? code(rewriteFrom(nav.from)) : '—'),
          nav.condition ? code(nav.condition) : '—',
          code(`${nav.loc.file}:${nav.loc.line}`),
        ]),
      ),
    mw.rewrites.length > 0 && '## Rewrites',
    mw.rewrites.length > 0 &&
      table(
        ['Path', 'Answered by', 'If', 'Source'],
        mw.rewrites.map((rw) => [
          code(rewriteFrom(rw.from)),
          rw.targetRouteId ? routeText(rw.targetRouteId) : code(urlText(rw.href)),
          rw.condition ? code(rw.condition) : '—',
          code(`${rw.loc.file}:${rw.loc.line}`),
        ]),
      ),
    '## Requests',
    sites.length === 0 ? 'The middleware sends no requests the scan found.' : requestTable(ctx, sites, from),
    ...sites.map((s) => requestSection(ctx, s, from, 3)),
  ])
}

// --- Postman collection (M15) -------------------------------------------------------------------

function postmanSourceText(source: PostmanSource): string {
  if (source.kind === 'cloud') return `Postman cloud${source.id ? ` (${code(source.id)})` : ''}`
  const what = source.kind === 'folder' ? 'collection folder' : 'file'
  return source.path ? `${what} ${code(source.path)}` : what
}

/** Request sites with a flag from the collection. */
function postmanSites(ctx: Ctx, kind: 'not-in-collection' | 'contract-mismatch'): RequestSite[] {
  return ctx.model.requests.filter((s) => s.flags.some((f) => f.kind === kind))
}

function postmanCounts(ctx: Ctx, contract: PostmanContract): string {
  const total = contract.requests.length
  const used = contract.requests.filter((r) => r.siteIds.length > 0).length
  return [
    `${used} of ${plural(total, 'request')} called by the app`,
    plural(total - used, 'unused endpoint'),
    `${plural(postmanSites(ctx, 'not-in-collection').length, 'request')} in the code not in the collection`,
    plural(postmanSites(ctx, 'contract-mismatch').length, 'contract mismatch', 'contract mismatches'),
  ].join(', ')
}

function postmanDoc(ctx: Ctx, contract: PostmanContract): string {
  const from = POSTMAN
  const requests = contract.requests
  const unused = requests.filter((r) => r.siteIds.length === 0)
  const missing = postmanSites(ctx, 'not-in-collection')
  const mismatched = postmanSites(ctx, 'contract-mismatch')
  // Grouped by folder, in collection order.
  const folders = new Map<string, PostmanRequest[]>()
  for (const r of requests) {
    const key = r.folder.join(' / ')
    const list = folders.get(key)
    if (list) list.push(r)
    else folders.set(key, [r])
  }
  const requestRef = (r: PostmanRequest) =>
    `[${text(r.name)}](#${anchorId(r.id)}) ${code(`${r.method} ${postmanPath(r)}`)}${r.folder.length > 0 ? ` (${text(r.folder.join(' / '))})` : ''}`
  return doc([
    `# Postman collection: ${text(contract.collection.name)}`,
    link('← Overview', from, README),
    facts([
      ['Collection', `${text(contract.collection.name)} · ${postmanSourceText(contract.collection.source)}`],
      [
        'Environment',
        contract.environment
          ? `${text(contract.environment.name)} · ${postmanSourceText(contract.environment.source)}`
          : undefined,
      ],
      ['Imported', time(contract.importedAt)],
      ['Summary', postmanCounts(ctx, contract)],
    ]),
    'The collection is the API contract: each request in the code is matched to a collection request by method and URL, or by its names and method when the scan could not resolve the URL. Types marked "from Postman examples" come from the saved responses, not the code.',
    '## Requests',
    requests.length === 0 && 'The collection has no requests.',
    ...[...folders].flatMap(([folder, list]) => [
      `### ${folder ? text(folder) : 'Not in a folder'}`,
      ...list.map((r) => postmanRequestSection(ctx, r, from)),
    ]),
    `## Unused endpoints (${unused.length})`,
    unused.length === 0
      ? 'Every collection request is called by the app.'
      : `No request in the code calls these.\n\n${unused.map((r) => `- ${requestRef(r)}`).join('\n')}`,
    `## Requests not in the collection (${missing.length})`,
    missing.length === 0
      ? "Every request the scan matched to the collection's APIs is in it."
      : `Requests in the code the collection has no request for.\n\n${table(
          ['Request', 'From', 'Status'],
          missing.map((s) => [siteLink(ctx, s, from), ownerText(ctx, s, from), statusText(ctx, s)]),
        )}`,
    `## Contract mismatches (${mismatched.length})`,
    mismatched.length === 0
      ? "No type in the code disagrees with the collection's examples."
      : `Types in the code that don't fit the collection's saved examples.\n\n${mismatched
          .flatMap((s) =>
            s.flags
              .filter((f) => f.kind === 'contract-mismatch')
              .map((f) => `- ${siteLink(ctx, s, from)}: ${text(f.message)}`),
          )
          .join('\n')}`,
  ])
}

