function recordedDoc(ctx: Ctx, recorded: RecordedFlow[]): string {
  const from = RECORDED
  return doc([
    '# Recorded flows',
    link('← Overview', from, README),
    'Named recordings you made in the dashboard, and walks that went somewhere the code did not predict (variants).',
    ...recorded.map((r) => recordedSection(ctx, r, from, 2)),
  ])
}

function recordedSection(ctx: Ctx, flow: RecordedFlow, from: string, level: number): string {
  const h = '#'.repeat(level)
  const inferred = flow.flowId ? ctx.index.flows.get(flow.flowId) : undefined
  return doc([
    `${h} ${anchor(flow.id)}${text(flow.name)}`,
    facts([
      ['Kind', flow.kind === 'named' ? 'named recording' : 'variant'],
      ['Follows', inferred ? flowLink(ctx, inferred, from) : undefined],
      ['Went elsewhere after step', flow.divergedAt !== undefined ? String(flow.divergedAt + 1) : undefined],
      ['Recorded', `${time(flow.startedAt)}${flow.endedAt ? ` – ${time(flow.endedAt)}` : ''}`],
    ]),
    flow.steps.length === 0
      ? 'No steps were recorded.'
      : table(
          ['#', 'Step'],
          flow.steps.map((s, i) => [String(i + 1), recordedStep(ctx, s, from)]),
          ['right', 'left'],
        ),
  ]).trimEnd()
}

function recordedStep(ctx: Ctx, step: RecordedStep, from: string): string {
  const routeText = (id: string | undefined) => {
    const route = id ? ctx.index.routes.get(id) : undefined
    return route ? ` on ${routeLink(ctx, route, from)}` : ''
  }
  switch (step.kind) {
    case 'interaction':
      return `User ${code(step.type)}${step.component ? ` in ${code(step.component)}` : ''} on ${text(step.target)}${routeText(step.routeId)}`
    case 'request': {
      const site = step.siteId ? ctx.index.requests.get(step.siteId) : undefined
      const status = step.status !== undefined ? ` → ${step.status}` : ''
      return `${code(`${step.method} ${step.path}`)}${status}${site ? ` (${siteLink(ctx, site, from)})` : ''}`
    }
    case 'navigate':
      return `${step.how} → ${code(step.path)}${routeText(step.routeId)}`
  }
}

// --- Types ------------------------------------------------------------------------------------

function typesDoc(ctx: Ctx): string {
  const from = TYPES
  const { index } = ctx
  const sections = ctx.model.types.map((type) => {
    const usage = index.typeUsage.get(type.id)
    const used: string[] = []
    if (usage) {
      for (const id of usage.props) used.push(`props of ${componentLink(ctx, id, from)}`)
      for (const id of usage.usedBy) used.push(`used in ${componentLink(ctx, id, from)}`)
      for (const id of usage.requests) {
        const site = index.requests.get(id)
        if (site) used.push(`request ${siteLink(ctx, site, from)}`)
      }
      for (const id of usage.inTypes) used.push(`in ${typeLink(ctx, id, from)}`)
    }
    return doc([
      `## ${anchor(type.id)}${text(type.name)}`,
      `${type.declarationKind} · ${code(`${type.definedAt.file}:${type.definedAt.line}`)}`,
      block('ts', declaration(type)),
      used.length > 0 ? `Used by: ${used.join(', ')}.` : 'Not used by any component or request directly.',
    ]).trimEnd()
  })
  return doc([
    '# Types',
    link('← Overview', from, README),
    ctx.model.types.length === 0
      ? 'No named project types are used by components or requests.'
      : `${plural(ctx.model.types.length, 'named type')}, fully resolved.`,
    ...sections,
  ])
}

// --- Issues -----------------------------------------------------------------------------------

const NOTE_GROUPS: { title: string; kinds: ScanNote['kind'][]; hint: string }[] = [
  {
    title: 'Type mismatches',
    kinds: ['type-mismatch'],
    hint: 'Captured data does not fit the declared types.',
  },
  {
    title: 'Needs a re-check',
    kinds: ['needs-recheck'],
    hint: 'The code changed after every capture. Use the app again to re-check.',
  },
  {
    title: 'Requests the scan could not fully resolve',
    kinds: ['request'],
    hint: 'Dynamic URLs, unknown methods or response types. Live capture fills these in.',
  },
  {
    title: 'Components and types the scan could not resolve',
    kinds: ['unresolved-component', 'unresolved-type', 'missing-page-component'],
    hint: '',
  },
]

function issueTotal(ctx: Ctx): number {
  const counts = ctx.data.verification?.counts
  return (
    ctx.index.notes.length + (counts ? counts.unmatched + counts.ambiguous : 0) + unconfirmedFlows(ctx).length
  )
}

function unconfirmedFlows(ctx: Ctx): Flow[] {
  const flows = ctx.data.flows
  if (!flows) return []
  return ctx.model.flows.filter((f) => flows.flows[f.id]?.status !== 'confirmed')
}

function issuesDoc(ctx: Ctx): string {
  const from = ISSUES
  const sections: (string | false)[] = [`# Issues`, link('← Overview', from, README)]
  const total = issueTotal(ctx)
  sections.push(total === 0 ? 'Nothing to check. 🎉' : `${plural(total, 'open item')}.`)

  for (const group of NOTE_GROUPS) {
    const notes = ctx.index.notes.filter((n) => group.kinds.includes(n.kind))
    if (notes.length === 0) continue
    sections.push(
      `## ${group.title} (${notes.length})`,
      group.hint,
      notes.map((n) => `- ${noteText(ctx, n, from)}`).join('\n'),
    )
  }

  const unmatched = ctx.data.captures.filter((c) => c.match?.status !== 'matched')
  const counts = ctx.data.verification?.counts
  if (counts && counts.unmatched + counts.ambiguous > 0) {
    const shown =
      unmatched.length < counts.unmatched + counts.ambiguous
        ? ` The newest ${unmatched.length} are listed.`
        : ''
    sections.push(
      `## Captures without a request site (${counts.unmatched + counts.ambiguous})`,
      `No scanned request site fits these (unmatched), or several fit equally well (ambiguous). Unmatched requests usually point at code the scanner missed. Assign them in the dashboard's Live screen.${shown}`,
      table(
        ['Time', 'Request', 'Status', 'Page', 'Match'],
        [...unmatched]
          .reverse()
          .map((c) => [
            time(c.timestamp),
            code(`${c.request.method} ${c.request.url}`),
            c.response ? String(c.response.status) : 'failed',
            c.pageUrl ? code(pathOf(c.pageUrl)) : c.origin,
            c.match?.status ?? 'unmatched',
          ]),
      ),
    )
  }

  const flows = unconfirmedFlows(ctx)
  if (flows.length > 0) {
    sections.push(
      `## Flows not confirmed (${flows.length})`,
      'Inferred from the code but not walked end to end in a recorded session yet.',
      flows
        .map((f) => `- ${flowLink(ctx, f, from)}: ${flowStatusText(ctx.data.flows?.flows[f.id], true)}`)
        .join('\n'),
    )
  }
  return doc(sections)
}

function noteText(ctx: Ctx, note: ScanNote, from: string): string {
  const where = code(`${note.file}${note.line ? `:${note.line}` : ''}`)
  let target = ''
  let message = note.message
  if (note.requestId) {
    const site = ctx.index.requests.get(note.requestId)
    if (site) {
      target = siteLink(ctx, site, from)
      // The message starts with the request label, which the link already shows.
      const prefix = `${requestLabel(site)}: `
      if (message.startsWith(prefix)) message = message.slice(prefix.length)
    }
  } else if (note.typeId) {
    target = typeLink(ctx, note.typeId, from)
  } else if (note.componentId) {
    target = componentLink(ctx, note.componentId, from)
  } else if (note.routeId) {
    const route = ctx.index.routes.get(note.routeId)
    if (route) target = routeLink(ctx, route, from)
  }
  return `${target ? `${target}: ` : ''}${text(message)} (${where})`
}

// --- Links and labels --------------------------------------------------------------------------

function routeLink(ctx: Ctx, route: Route, from: string): string {
  const file = ctx.names.route(route.id)
  const label = code(route.kind === 'page' ? route.path : route.path)
  return file ? link(label, from, file) : label
}

function componentLink(ctx: Ctx, id: string, from: string): string {
  const c = ctx.index.components.get(id)
  const file = ctx.names.component(id)
  const label = code(c?.name ?? id)
  return file ? link(label, from, file) : label
}

function flowLink(ctx: Ctx, flow: Flow, from: string): string {
  const file = ctx.names.flow(flow.id)
  return file ? link(text(flow.name), from, file) : text(flow.name)
}

function typeLink(ctx: Ctx, id: string, from: string, label?: string): string {
  const type = ctx.index.types.get(id)
  return link(code(label ?? type?.name ?? id), from, TYPES, anchorId(id))
}

/** Link to where a request is documented: its component, its route handler, or its caller. */
function siteLink(ctx: Ctx, site: RequestSite, from: string): string {
  const home = siteHome(ctx, site)
  const label = code(requestLabel(site))
  return home ? link(label, from, home, anchorId(site.id)) : label
}

function siteHome(ctx: Ctx, site: RequestSite, seen = new Set<string>()): string | undefined {
  if (site.origin === 'component' && site.componentId) return ctx.names.component(site.componentId)
  if (site.origin === 'route-handler' && site.routeId) return ctx.names.route(site.routeId)
  const caller = ctx.callers.get(site.id)
  if (!caller || seen.has(caller.id)) return undefined
  return siteHome(ctx, caller, new Set([...seen, site.id]))
}

/** Who sends it: the component, the route handler, or the server action. */
function ownerText(ctx: Ctx, site: RequestSite, from: string): string {
  if (site.origin === 'component' && site.componentId) return componentLink(ctx, site.componentId, from)
  if (site.origin === 'route-handler' && site.routeId) {
    const route = ctx.index.routes.get(site.routeId)
    return `${site.handlerMethod ?? '?'} ${route ? routeLink(ctx, route, from) : '?'}`
  }
  return `server action ${code(site.serverAction?.name ?? '?')}`
}

function statusText(ctx: Ctx, site: RequestSite): string {
  const n = ctx.data.verification?.sites[site.id]?.captures ?? 0
  const captures = n > 0 ? ` (${plural(n, 'capture')})` : ''
  switch (site.status) {
    case 'verified':
      return `✓ verified${captures}`
    case 'mismatch':
      return `✗ type mismatch${captures}`
    case 'needs-recheck':
      return `↻ needs re-check${captures}`
    case 'inferred':
      return 'inferred'
  }
}

function statusCounts(sites: RequestSite[]): string {
  if (sites.length === 0) return '—'
  const n = (status: RequestSite['status']) => sites.filter((s) => s.status === status).length
  const parts = [
    n('verified') > 0 && `✓ ${n('verified')} verified`,
    n('mismatch') > 0 && `✗ ${n('mismatch')} mismatch`,
    n('needs-recheck') > 0 && `↻ ${n('needs-recheck')} re-check`,
    n('inferred') > 0 && `${n('inferred')} inferred`,
  ]
  return parts.filter(Boolean).join(', ')
}
